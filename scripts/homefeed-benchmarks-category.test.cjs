/**
 * 분야 분류 — 인물 · 사건 소재가 낱말 하나로 엉뚱한 분야에 가지 않게(2026-11-15).
 * 실측(판 1,000장): 고경표 음주운전 10장이 '운전' 하나로 자동차·IT, 기아 타이거즈 FA 소식이 '기아' 하나로 자동차·IT,
 * 배우 소식이 요약 속 '공항' · 드라마 소식이 요약 속 '건강' 한 번으로 여행·생활 · 건강.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const { category } = require('./homefeed-benchmarks-core.cjs');

test('음주운전 · 뺑소니 같은 사건은 자동차·IT 가 아니라 사회·이슈다', () => {
  assert.equal(category('촬영 다 끝냈는데 어쩌라고.. 고경표 음주운전, 박보검 무슨 죄?'), '사회·이슈');
  assert.equal(category('광명 환경미화원 뺑소니 사망, 50대 운전자 체포 후 사고 뒤 음주 주장'), '사회·이슈');
  assert.equal(category('요즘 다들 이렇게 한다는 그것', [], '새벽에 음주운전 사고를 낸 배우가 청소차를 들이받았다'), '사회·이슈');
});

test('운전 · 차 이야기는 그대로 자동차·IT 다', () => {
  assert.equal(category('초보운전 주차 꿀팁'), '자동차·IT');
  assert.equal(category('운전자보험 비교 후기'), '자동차·IT');
  assert.equal(category('기아 EV5 벌써 신차 나오나'), '자동차·IT');
  assert.equal(category('기아 쏘렌토 하이브리드 연비'), '자동차·IT');
});

test('기아 타이거즈 선수 소식은 자동차·IT 가 아니다 — 기아는 차 단어와 같이 있을 때만 차 이야기', () => {
  assert.equal(category('원태인이 기아로 간다고? 심재학 단장이 직접 이름 꺼낸 뒤', [], '프로야구 FA 시장에서 투수 원태인을 두고 KBO 구단 단장이 말했다'), '스포츠·게임');
  assert.equal(category('김호령 기아 FA조건 2번이나 거절한 이유', [], '프로야구 외야수 김호령은 FA 등급을 받았다'), '스포츠·게임');
  assert.equal(category('기아타이거즈 김도영 41홈런'), '스포츠·게임');
});

test('약한 말(선수 · 게임 · 공항 · 교통 · 날씨)은 다른 분야의 뚜렷한 단서가 없을 때만 분야를 정한다', () => {
  assert.equal(category('둘 다 1990년생 아이돌인데.. 중국은 라틴댄스 선수 출신, 한국은 짐승돌로 데뷔한 두 배우'), '문화·연예');
  assert.equal(category('2027 KBO FA 선수 명단 총정리, 10개 구단별 전망'), '스포츠·게임');
  assert.equal(category('제주공항 국내선 수하물 규정 총정리'), '여행·생활');
  assert.equal(category('꽈당 넘어졌다고? 전희미 논란', [], '전희미가 공항에서 넘어졌다는 소식에 팬들이 분노했다. 배우 전희미가 공항에서 넘어진 영상'), '문화·연예');
});

test('요약에서는 서로 다른 단서 낱말이 가장 많은 쪽이 이긴다 — 한 번 나온 곁가지 말이 정하지 않는다', () => {
  const summary = '왕 앞에 선 장군 한 사람 때문에 대하사극의 공기가 달라졌습니다. KBS 대하드라마 문무 1회. 드라마 속 왕의 건강이 나빠지며 시청자들은 이 드라마의 배우 장혁에 주목했다.';
  assert.equal(category('문무 1회 연개소문 vs 영류왕, 누가 고구려를 지키려 했나?', [], summary), '문화·연예');
  assert.equal(category('요즘 다들 이렇게 한다는 그것', [], '신형 그랜저를 한 달 타 보니 연비가 이렇게 나왔습니다'), '자동차·IT');
});

test('연예 소식 단서 — 열애 · 재결합설 · 소속사', () => {
  assert.equal(category('뷔, 제니와 재결합설 보도 이후 SNS 공개…사진 속 뜻밖의 장면', [], '방탄소년단 뷔가 11월 12일 자신의 SNS에 남긴 한마디. 런던 공항에서 찍은 사진'), '문화·연예');
  assert.equal(category('소속사 입장 발표, 열애설 인정'), '문화·연예');
});

test('예전 규칙은 그대로 — 제목 단서가 출처 주제보다 먼저, 요약 없으면 블로그 주제', () => {
  assert.equal(category('손흥민 결승골 터진 순간 아시안게임', ['IT/차테크']), '스포츠·게임');
  assert.equal(category('요즘 다들 이렇게 한다는 그것', ['건강 상식']), '건강');
  assert.equal(category('요즘 다들 이렇게 한다는 그것', ['IT/차테크'], '내용 요약 한 줄'), '사회·이슈');
});
