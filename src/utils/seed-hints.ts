/*
 * 어느 주제든 버리는 말.
 *   · 광고주 거래어 — 대여·대관·섭외·업체·대행·도매·주문제작·대출·요금제·셋톱·구인구직
 *   · 매체 불법 복제·성인물 — 영화/드라마/애니/웹툰/음원 + 다운·사이트, 토렌트·웹하드, AV·야설
 * '성인'을 통째로 막으면 성인피아노학원·성인미술학원이 죽고(실측), '무료…사이트'를
 * 통째로 막으면 무료폰트사이트가 죽는다 — 그래서 성인용품·매체 복제만 콕 집어 막는다.
 */
export const HINT_DENY = new RegExp([
  '대출|카드론|대여|대관|섭외|용역|대행|도매|주문제작|업체|OEM',
  '요금제|셋톱|셋탑|유선설치|알바|아르바이트|구인구직|인턴',
  '성인용품|AV영화|야설|19금|토렌트|웹하드',
  '(?:영화|드라마|애니|일드|미드|중드|VOD|웹툰|만화|음원)(?:무료)?(?:다운|보기사이트|다시보기사이트|사이트)',
].join('|'));

const NEVER = /$^/;

/**
 * 이 행을 이 주제의 힌트 씨앗으로 담을까.
 *   ① 거래어·복제물이면 버린다
 *   ② 말 규칙(seed-db.KEYWORD_TOPIC)이 주제를 정하면 그 판정을 따른다 —
 *      뮤지컬은 공연·전시 규칙에 걸리니 스타·연예인 아래에서 와도 안 담고,
 *      이터널리턴은 게임 규칙에 걸리니 닻이 없어도 게임에 담는다
 *   ③ 아니면 그 주제의 닻이 있어야 담는다
 * 걸러진 행은 창고에 안 들어가므로, 같은 말이 뒤 머리말(제 주제)에서 다시 오면
 * 그때 담긴다 — 영화 머리말이 버린 '드라마추천'을 드라마 머리말이 담는다.
 */
export function keepHintRow(topic: string, keyword: string): boolean {
  const compact = String(keyword || '').replace(/\s+/g, '');
  if (!compact || HINT_DENY.test(compact)) return false;
  // 출처 없이 물으면 말 규칙만 답한다 — 힌트 출처를 달면 늘 그 주제라고 답해 의미가 없다.
  const byWord = topicOfSeed({ keyword: compact, searchVolume: 0 });
  if (byWord) return byWord === topic;
  return (HINT_ANCHORS[topic] ?? NEVER).test(compact);
}

/*
 * 같은 말이 여러 창구에서 오면 어느 출처를 남기나.
 *
 * 창고를 세어 보니 업종 창구 행 84,882개 중 21,899개가 먼저 긁은 월·시즌 창구에
 * 가려져 출처를 잃었다. 월·시즌 출처는 주제가 없어 라우팅이 안 되므로, 그 말이
 * 업종에서도 왔다는 사실이 통째로 버려진 것이다. 주제를 아는 출처가 이겨야 한다.
 *   hint  3  주제를 직접 가리킨다
 *   biztp 2  업종 매핑으로 주제를 안다
 *   month/event 1  주제가 없다(말 규칙에만 기댄다)
 * 같은 급이면 먼저 만난 것을 남긴다 — 옛 동작 그대로라 기존 창고와 어긋나지 않는다.
 */
const SOURCE_RANK: Readonly<Record<string, number>> = Object.freeze({ hint: 3, biztp: 2, month: 1, event: 1 });

function rankOf(tag: string): number {
  const prefix = tag.split(':')[0];
  return SOURCE_RANK[prefix] ?? 0;
}

export function preferSource(previous: string | undefined, next: string | undefined): string {
  const prev = String(previous || '');
  const nxt = String(next || '');
  if (!prev) return nxt;
  if (!nxt) return prev;
  return rankOf(nxt) > rankOf(prev) ? nxt : prev;
}

export interface WarehouseLike {
  builtAt?: string;
  sources?: Record<string, unknown>;
}

/**
 * 창고를 다시 긁어야 하나.
 *   · 3일(월·금 갱신)이 넘었으면 다시
 *   · 힌트 창구가 없는 옛 꼴이면 **신선해도** 다시 — 힌트를 연 날 레포 창고는
 *     하루 전 것이라, 날짜만 보면 건너뛰고 열 주제가 다음 회차까지 또 0개다
 *   · 없거나 날짜가 깨졌으면 다시
 */
export function warehouseNeedsRebuild(
  previous: WarehouseLike | null | undefined,
  options: { maxAgeDays: number; now?: Date },
): boolean {
  if (!previous || typeof previous !== 'object') return true;
  const builtAt = Date.parse(String(previous.builtAt || ''));
  if (!Number.isFinite(builtAt)) return true;
  const now = options.now ?? new Date();
  const ageDays = (now.getTime() - builtAt) / 86400000;
  if (ageDays >= options.maxAgeDays) return true;
  const sources = previous.sources;
  if (!sources || typeof sources !== 'object' || !('hint' in sources)) return true;
  return false;
}
