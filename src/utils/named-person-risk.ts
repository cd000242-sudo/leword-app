/**
 * 실명 키워드 판정 — "내가 써도 되는 글인가".
 *
 * 왜 필요한가 (사장님 지적, 2026-08-10):
 *   보드에 '정형외과 임형태'가 올라왔다. 자리는 실제로 비어 있지만, **그 글은
 *   임형태라는 분 본인이나 그 병원이 써야 하는 글이다.** 남이 추측으로 쓰면
 *   틀린 정보가 되고, 의료인 실명은 의료광고 심의·명예훼손까지 걸린다.
 *
 *   자리가 비어 있는 이유가 "아무도 안 써서"가 아니라 **"당사자 말고는 쓸 수
 *   없어서"** 인 경우가 있다. 숫자로는 이 둘이 구분되지 않는다.
 *
 * 무엇을 막고 무엇을 두는가:
 *   막는다 — 사람 실명이 붙은 전문직·기관('정형외과 임형태', '김철수 변호사')
 *   둔다   — 상표·제품명('강아지이발기 에이블미', '멜론티켓'). 제품 후기는
 *            누구나 쓸 수 있고 실제로 그렇게 쓴다.
 */

/** 실명이 붙으면 당사자만 쓸 수 있는 자리가 되는 곳. */
const PROFESSION_TOKENS = [
  '정형외과', '치과', '한의원', '의원', '병원', '클리닉', '피부과', '안과', '이비인후과',
  '산부인과', '소아과', '신경과', '외과', '내과', '약국', '한방병원',
  '변호사', '법무사', '세무사', '노무사', '회계사', '감정평가사', '행정사',
  '원장', '대표원장', '교수', '강사', '선생님',
] as const;

/**
 * 한국인 성씨. 이름 모양을 가리는 데만 쓴다.
 *
 * 성씨 목록이 없으면 '정형외과 예약'의 '예약'도 이름으로 잡힌다 —
 * 실측에서 그런 오탐을 이미 한 번 겪었다(`약` 한 글자 사건).
 */
const SURNAMES = [
  '김', '이', '박', '최', '정', '강', '조', '윤', '장', '임', '한', '오', '서', '신', '권',
  '황', '안', '송', '류', '전', '홍', '고', '문', '양', '손', '배', '백', '허', '유', '남',
  '심', '노', '하', '곽', '성', '차', '주', '우', '구', '민', '진', '지', '엄', '채', '원',
  '천', '방', '공', '현', '함', '변', '여', '추', '도', '소', '석', '선', '설', '마', '길',
  '연', '위', '표', '명', '기', '반', '왕', '금', '옥', '육', '인', '맹', '제', '모', '탁',
  '국', '어', '은', '편', '용',
] as const;

const SURNAME_SET = new Set<string>(SURNAMES);

/**
 * 성씨로 시작하지만 이름이 아닌 흔한 말.
 *
 * 성씨 목록만으로는 '정형외과 예약 방법'의 '방법'('방'씨)이 이름으로 잡힌다.
 * 실측에서 바로 걸렸다. 이 바닥에서 자주 부딪히는 것만 모아 둔다.
 */
const NOT_NAMES = new Set([
  '방법', '비용', '가격', '예약', '진료', '주차장', '주차비', '문의처', '고객님',
  '오전반', '오후반', '진료비', '상담실', '주말반', '야간반', '이용법', '이용료',
  '고객센터', '주소지', '전화번호', '예약금', '진료과', '안내문', '남자용', '여자용',
  '무료로', '최저가', '차이점', '순위표', '후기글', '기준표', '신청서', '인기순',
]);

/**
 * 이름처럼 생겼는가 — 성씨 한 글자 + 한글 두 글자.
 *
 * **세 글자만 센다.** 두 글자까지 열면 '방법'·'비용'처럼 성씨로 시작하는 흔한
 * 낱말이 전부 이름이 된다. 두 글자 이름(김구 등)을 놓치지만, 여기서는
 * 놓치는 쪽이 잘못 막는 쪽보다 낫다 — 공급이 이미 얇다.
 */
function looksLikePersonName(token: string): boolean {
  if (!/^[가-힣]{3}$/.test(token)) return false;
  if (NOT_NAMES.has(token)) return false;
  return SURNAME_SET.has(token[0]);
}

export interface NamedPersonRisk {
  /** 당사자만 쓸 수 있는 자리로 보이는가. */
  risky: boolean;
  /** 무엇을 보고 그렇게 봤는지. 화면·로그에 그대로 쓴다. */
  reason: string;
}

/**
 * 키워드가 특정인의 실명에 걸려 있는지 본다.
 *
 * 전문직 낱말과 이름 모양이 **함께** 있어야 한다. 하나만으로는 안 된다 —
 * '정형외과 예약'은 멀쩡하고, '김치찌개 레시피'도 멀쩡해야 한다.
 */
export function judgeNamedPersonRisk(keyword: string): NamedPersonRisk {
  const tokens = String(keyword || '').trim().split(/\s+/).filter(Boolean);
  if (tokens.length < 2) return { risky: false, reason: '' };

  const compact = tokens.join('');
  const profession = PROFESSION_TOKENS.find((token) => compact.includes(token));
  if (!profession) return { risky: false, reason: '' };

  // 전문직 낱말 자체를 이름 후보에서 뺀다. '정형외과 임형태'에서 '임형태'만 남는다.
  const nameToken = tokens.find(
    (token) => looksLikePersonName(token) && !PROFESSION_TOKENS.some((p) => token.includes(p)),
  );
  if (!nameToken) return { risky: false, reason: '' };

  return {
    risky: true,
    reason: `'${nameToken}' — ${profession} 실명으로 보인다. 당사자만 쓸 수 있는 글이다`,
  };
}
