/**
 * 32종 전체 커버리지 표.
 * naver-blog-topics.ts 를 돌면서 만들기 때문에 주제가 추가·삭제되면 여기도 따라간다.
 */
export const BLOG_TOPIC_COVERAGE: readonly BlogTopicCoverage[] = Object.freeze(
  NAVER_BLOG_TOPICS.map((topic: NaverBlogTopic) => Object.freeze({
    topic: topic.label,
    minerCategories: MINER_CATEGORIES[topic.label] ?? [],
    seedIntents: SUPPLEMENTAL_INTENTS[topic.label] ?? [],
    seedTerms: SEED_TERMS[topic.label] ?? [],
  })),
) as readonly BlogTopicCoverage[];

/**
 * 발굴 근거가 하나도 없는 주제.
 * 배치가 시작할 때 이걸 찍어서 "0건인데 왜 0건인지"를 사람이 알게 한다.
 * 비어 있어야 정상이다.
 */
export function topicsWithoutCoverage(): string[] {
  // 씨앗어가 없으면 확장의 출발점이 없어 반드시 0건이 된다.
  // 카테고리·의도어가 있어도 씨앗이 없으면 소용없으므로 기준은 씨앗어다.
  return BLOG_TOPIC_COVERAGE.filter((entry) => entry.seedTerms.length === 0).map((entry) => entry.topic);
}

/**
 * 씨앗어 길이 점검.
 * 검색광고 hintKeywords 는 15자를 넘으면 잘려서 **엉뚱한 키워드의 연관어**가 온다.
 * 조용히 다른 결과를 받아 쿼터만 태우는 실패라 실행 전에 걸러야 한다.
 */
export function oversizedSeedTerms(): Array<{ topic: string; term: string }> {
  const bad: Array<{ topic: string; term: string }> = [];
  for (const entry of BLOG_TOPIC_COVERAGE) {
    for (const term of entry.seedTerms) {
      if (term.replace(/\s+/g, '').length > 15) bad.push({ topic: entry.topic, term });
    }
  }
  return bad;
}

/** 발굴기 카테고리 하나가 어떤 주제로 표기돼야 하는지. 보드 라벨링에 쓴다. */
export function topicForMinerCategory(categoryId: string): string | null {
  const hit = BLOG_TOPIC_COVERAGE.find((entry) => entry.minerCategories.includes(categoryId));
  return hit ? hit.topic : null;
}

export function coverageForTopic(topic: string): BlogTopicCoverage | null {
  return BLOG_TOPIC_COVERAGE.find((entry) => entry.topic === topic) ?? null;
}

/** 배치가 실제로 돌 발굴기 카테고리 전체(중복 제거). */
export function allMinerCategories(): string[] {
  const seen = new Set<string>();
  for (const entry of BLOG_TOPIC_COVERAGE) {
    for (const id of entry.minerCategories) seen.add(id);
  }
  return [...seen];
}
