import { describe, expect, it } from 'vitest';
import { judgeAnswerCardKeyword } from '../preemption-supply-guards';

/**
 * 카드 답 가드 — "네이버가 카드로 직접 답하는 검색어"를 BD 태우기 전에 거른다.
 *
 * 왜(사장님 2026-09-08 "블로그로 날씨 같은 걸 찾아볼까? 프로필을 검색하지만 블로그를
 * 찾아보는 사람이 있니?"): 발행 보드 122행 중 30행이 이 부류였고 그중 24행이
 * 'xx cc 날씨'였다. 검색량÷문서수는 크지만(아무도 골프장 날씨 글을 안 쓴다) 검색한
 * 사람은 날씨 카드 한 줄로 만족하고 나간다 — 자리가 빈 게 아니라 쓸 게 없는 것이다.
 * 보강 AI 도 이미 "만족 조건이 전부 '한 줄 사실'"이라 판정했는데 등급이 못 봤다.
 *
 * 유통기한 가드처럼 좁게 유지한다. 한글은 낱말 경계가 없어서 '나이'를 넣으면
 * 톤틴연금 가입'나이'·쳇지피티 재미'나이'(Gemini)·'나이'스차저가 걸린다 — 실제 보드에
 * 있던 행들이다. 그래서 끝맺음(`$`)으로만 잡고 사람 사실(나이·키)은 안 넣는다.
 * 그건 SERP 인물 카드 마커(실측)와 수익 판정이 잡는다.
 */
describe('카드 답 가드 — 실제 보드에 실렸던 행', () => {
    const cards = [
        // 날씨 카드 — 보드 26행 중 대표
        '모나크cc 날씨', '경주cc날씨', '변산반도 날씨', '진하해수욕장 날씨', '블랙스톤이천 날씨',
        '이천실크밸리cc 날씨', '비에비스타cc날씨',
        // 인물 카드
        '송강 프로필', '용혜인 프로필',
        // 증권 카드
        'etl 기업 주가',
        // 그 밖의 카드 — 운세·로또·플레이스·지도·사전·가사·배송조회
        '오늘의운세', '띠별운세', '로또당첨번호', '로또 당첨번호 조회',
        '서울역 주소', '스타벅스 영업시간', '제주도 지도', '사랑 뜻', '고양이 영어로',
        '밤양갱 가사', 'cj 택배조회', '로젠택배조회', '씨유 편의점 택배 조회',
        '오늘 환율', '금시세', '삼성전자 주가',
        // 오늘의 추천키워드 실측(2026-09-08)에서 새어 나온 카드 — 시세·달력·복권·증권 화면·진료과
        '리플시세', '중고차 시세', '아파트 시세', '종합주가지수', '음력달력', '연금복권', '검색상위종목', '이비인후과', '동네 피부과', '약국',
    ];
    for (const keyword of cards) {
        it(`${keyword} — 카드가 답한다`, () => {
            const verdict = judgeAnswerCardKeyword(keyword);
            expect(verdict.answerCard).toBe(true);
            expect(verdict.reason.length).toBeGreaterThan(5);
        });
    }
});

describe('카드 답 가드 — 블로그 글이 되는 말은 남긴다', () => {
    const writable = [
        // 실제 보드에서 '나이' 부분일치로 잘못 걸릴 뻔한 행
        '톤틴연금 가입나이', '쳇지피티 재미나이', '나이스차저 환경부카드', '나이스차저 요금',
        // 부분일치 함정
        '나이키', '키보드 추천', '사전예약', '지도자', '결혼식 하객룩', '지갑 분실 찾는법',
        // 카드 낱말이 들어가도 뒤에 말이 붙으면 글감이다
        '금시세 전망', '로또 명당', '운세 보는법', '날씨 옷차림', '환율 전망 2026', '주가 전망',
        '가사 분담', '가사도우미 비용', '주소 변경 방법', '영업시간 변경 신고',
        // 카드 낱말 뒤에 말이 붙으면 글감이다
        '리플시세 전망', '중고차 시세 조회 방법', '이비인후과 추천', '피부과 시술 후기', '달력 만들기', '연금복권 당첨 확률',
        // 평범한 글감
        '몬스테라 무름병', '실업급여 조건', '넷플릭스 요금제 비교', '드라마 결말 해석',
    ];
    for (const keyword of writable) {
        it(`${keyword} — 남긴다`, () => {
            expect(judgeAnswerCardKeyword(keyword).answerCard).toBe(false);
        });
    }

    it('빈 값은 카드가 아니다', () => {
        expect(judgeAnswerCardKeyword('').answerCard).toBe(false);
        expect(judgeAnswerCardKeyword(undefined as unknown as string).answerCard).toBe(false);
    });
});
